"""Regenerate STATUS.md from current CAD metadata, CHANGELOG.md and git log.

The active metadata is the current-state source. Historical rating paragraphs
must not be selected merely because they occur last in a document.
"""
import json
import pathlib
import subprocess

R = pathlib.Path(__file__).resolve().parent.parent


def render_status(root=R, recent_commits=None):
    active = json.loads((root / 'project/cad/N2/active_metadata.json').read_text())
    req, screen = active['current_requirements'], active['current_analysis']
    cl = (root / 'CHANGELOG.md').read_text().split('\n## ', 1)[1].split('\n## ', 1)[0]
    if recent_commits is None:
        recent_commits = subprocess.run(
            ['git', 'log', '-n', '15', '--date=short', '--pretty=- %ad `%h` %s'],
            cwd=root, capture_output=True, text=True, check=True,
        ).stdout
    docs = '\n'.join(f'- [{p.stem}](docs/{p.name})' for p in sorted((root / 'docs').glob('*.md')))
    return f"""# N2 status

_Auto-generated by `site/build_status.py` on push. Don't edit by hand._

**Current design:** {active['geometry_revision']} — planned {active['prototype_material']} bench prototype, four printed parts.

**Provisional requirement:** {req['payload_mass_kg']:.3f} kg carried mass including removable adapter and its hardware, {req['load_factor_g']:g} g, SF {req['safety_factor']:g}; **{req['design_load_N']:.1f} N design load** and **{req['qualification_load_N']:.1f} N sacrificial qualification load**. Straight +Z pull only. See [requirements](docs/requirements.md).

**Analysis screen:** {screen['stress_screen_N']:.2f} N, adapter governs the two analyzed straight-pull support states. Dividing by SF 2 gives {screen['sf2_allowance_N']:.2f} N as an arithmetic comparison; **no working-load rating is assigned**. This scales PLA stress thresholds by 47/31 for PAHT-CF and assumes ideal full receiver backing. It is not a direct anisotropic PAHT-CF analysis or a measured breaking load. See [evidence and limits](docs/provisional-load-rating.md).

**Physical status:** nothing printed or tested. Next: inspect and print the current P14 files, measure fit and actuator force, then follow the staged [bench test plan](docs/test-plan.md). Unlocking and actual adapter clearance are separate test outcomes.

## Latest change

### {cl.strip()}

## Recent commits

{recent_commits}
## Docs

{docs}
- [CHANGELOG](CHANGELOG.md)
- Print STLs: [project/cad/N2](project/cad/N2) (GitHub shows STL files in its 3D viewer)
"""


if __name__ == '__main__':
    (R / 'STATUS.md').write_text(render_status())
