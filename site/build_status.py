"""Regenerate STATUS.md at the repo root from CHANGELOG.md, docs/ and git log."""
import re, subprocess, pathlib
R = pathlib.Path(__file__).resolve().parent.parent
rating = (R / 'docs/provisional-load-rating.md').read_text()
m = re.findall(r'^\*\*(N2 P\d+ hardpoint: .*?)\*\*', rating, re.M)
cl = (R / 'CHANGELOG.md').read_text().split('\n## ')[1]
log = subprocess.run(['git', 'log', '-n', '15', '--date=short', '--pretty=- %ad `%h` %s'], cwd=R, capture_output=True, text=True).stdout
docs = '\n'.join(f'- [{p.stem}](docs/{p.name})' for p in sorted((R / 'docs').glob('*.md')))
(R / 'STATUS.md').write_text(f"""# N2 status

_Auto-generated by `site/build_status.py` on push. Don't edit by hand._

**Provisional rating:** {m[-1] if m else 'see docs/provisional-load-rating.md'}

**Status:** design + analysis only, nothing printed or tested. Next: print the current receiver and run the [proof-load test](docs/test-plan.md).

## Latest change
### {cl.strip()}

## Recent commits
{log}
## Docs
{docs}
- [CHANGELOG](CHANGELOG.md)
- Print STLs: [project/cad/N2](project/cad/N2) (GitHub shows STL files in its 3D viewer)
""")
